"""Resolve included Markdown links relative to their repository source."""

import importlib.util
import ipaddress
import json
import posixpath
import re
import struct
import sys
import zlib
from pathlib import Path
from urllib.parse import urlsplit

from markdown import Markdown

ROOT = Path(__file__).resolve().parents[1]
# A tool page's search entry is the only one whose location is a catalog directory followed by a
# stable tool name, optionally with an anchor.
TOOL_PAGE = re.compile(
    r"(?P<directory>features|platform)/(?P<tool>revit_[a-z0-9_]+)/?$"
)

# Each entry maps the repository files that back a documentation page to its Chinese and English page, so a
# link to any of those files resolves to the page the current language build actually has.
SOURCES = [
    (["README.md"], "index.md", "index.en.md"),
    (["server/README.zh.md", "server/README.md"], "server.md", "server.en.md"),
    (
        ["CONTRIBUTING.zh.md", "CONTRIBUTING.md"],
        "contributing.md",
        "contributing.en.md",
    ),
    (["SECURITY.zh.md", "SECURITY.md"], "security-policy.md", "security-policy.en.md"),
    (["CHANGELOG.zh.md", "CHANGELOG.md"], "changelog.md", "changelog.en.md"),
]


def on_page_markdown(markdown, page, config, files):
    root = Path(config.config_file_path).parent
    for sources, chinese_page, english_page in SOURCES:
        if page.file.src_uri == chinese_page:
            source = sources[0]
            break
        if page.file.src_uri == english_page:
            source = sources[-1]
            break
    else:
        source = f"docs/{page.file.src_uri}"
    # Expand snippets before MkDocs validates links, retaining one source of content.
    processor = Markdown(
        extensions=["pymdownx.snippets"],
        extension_configs={
            "pymdownx.snippets": {"base_path": [str(root)], "check_paths": True}
        },
    )
    markdown = "\n".join(processor.preprocessors["snippet"].run(markdown.splitlines()))
    # One repository file can back more than one page (the README backs the Chinese landing page and the
    # English home), so keep every candidate and prefer the one this language build actually has.
    pages: dict[str, list[str]] = {}
    for sources, chinese_page, english_page in SOURCES:
        for repository_file in sources:
            pages.setdefault(repository_file, []).extend([chinese_page, english_page])
    src_uri = page.file.src_uri
    if src_uri in ("index.md", "index.en.md"):
        # The landing page is generated by tools/site/landing.py, so its "edit this page" link has to
        # point at the generator: editing index.md or README.md would be overwritten on the next run.
        page.edit_url = f"{config.repo_url}/blob/main/tools/site/landing.py"
    elif src_uri.startswith("features/"):
        # Same rule for the generated feature pages.
        page.edit_url = f"{config.repo_url}/blob/main/tools/site/generate_features.py"
    elif src_uri.startswith("platform/"):
        # Same rule for the platform catalog, which tools/site/platform_catalog.py generates.
        page.edit_url = f"{config.repo_url}/blob/main/tools/site/platform_catalog.py"
    elif any(src_uri == pair[1] or src_uri == pair[2] for pair in SOURCES):
        # Hand-written pages keep the edit link of the repository file that holds their content.
        page.edit_url = f"{config.repo_url}/edit/main/{source}"

    def resolve(target):
        if target.startswith(config.site_url):
            relative = target[len(config.site_url) :]
            path, separator, anchor = relative.partition("#")
            candidate = f"{path.rstrip('/')}.md" if path else "index.md"
            if files.get_file_from_path(candidate):
                return candidate + (separator + anchor if separator else "")
        url = urlsplit(target)
        if url.scheme or url.netloc or not url.path:
            return target
        path = posixpath.normpath(posixpath.join(posixpath.dirname(source), url.path))
        suffix = (f"?{url.query}" if url.query else "") + (
            f"#{url.fragment}" if url.fragment else ""
        )
        if path in pages:
            for candidate in pages[path]:
                if files.get_file_from_path(candidate):
                    return candidate + suffix
            return pages[path][0] + suffix
        if path.startswith("docs/"):
            return (
                posixpath.relpath(path[5:], posixpath.dirname(page.file.src_uri))
                + suffix
            )
        if (root / path).is_file():
            return f"{config.repo_url}/blob/main/{path}{suffix}"
        return target

    # Pages generated by tools/site/landing.py mark shared assets with @@ROOT@@; resolve it before
    # link resolution so the result is an ordinary relative path.
    markdown = markdown.replace("@@ROOT@@", site_root_prefix(page))
    markdown = re.sub(
        r"(\]\()([^\s)]+)(\))", lambda m: m[1] + resolve(m[2]) + m[3], markdown
    )
    markdown = re.sub(
        r'(\b(?:src|srcset)=")([^"]+)(")',
        lambda m: m[1] + resolve(m[2]) + m[3],
        markdown,
    )
    return markdown


def site_root_prefix(page) -> str:
    """Relative path from one page back to the site root, for assets shared by every language.

    MkDocs already reports the locale as part of `page.url` (`en/`, `en/features/`), which is why the
    theme's own `url` filter emits `../assets/...` on `/en/`. Raw HTML from the page generator cannot
    use that filter, so the same count of `../` is derived from the page URL here.
    """
    depth = len([part for part in page.url.split("/") if part])
    return "../" * depth


_URL_BLOCK = re.compile(r"<url>.*?</url>", re.DOTALL)
_LOC = re.compile(r"<loc>([^<]+)</loc>")


def _write_directory_sitemaps(site: Path, site_url: str = "") -> int:
    """Give every directory with a page its own sitemap.

    Material resolves the alternate-language lookup as `new URL("sitemap.xml", pageUrl)`, so a page at
    /features/revit_ping/ asks for /features/revit_ping/sitemap.xml and gets a 404. Every directory
    that holds a page therefore gets its own sitemap containing that directory's entries, so the
    lookup succeeds and stays truthful.

    A deployment under a path — a GitHub Pages project site, for one — prefixes every location with
    that path, so it is stripped before the directory is resolved against the build tree.
    """
    sitemap = site / "sitemap.xml"
    if not sitemap.is_file():
        return 0
    text = sitemap.read_text(encoding="utf-8")
    start = text.find("<urlset")
    if start < 0:
        return 0
    head, open_end = text[:start], text.find(">", start) + 1
    preamble, open_tag = head, text[start:open_end]
    groups: dict[str, list[str]] = {}
    base = urlsplit(site_url).path.rstrip("/") if site_url else ""
    for block in _URL_BLOCK.findall(text):
        found = _LOC.search(block)
        if not found:
            continue
        path = urlsplit(found.group(1)).path
        if base and (path == base or path.startswith(base + "/")):
            path = path[len(base) :] or "/"
        directory = path if path.endswith("/") else posixpath.dirname(path) + "/"
        if directory != "/":
            groups.setdefault(directory, []).append(block.strip())
    written = 0
    for directory, blocks in groups.items():
        target = site / directory.lstrip("/") / "sitemap.xml"
        if target == sitemap or not target.parent.is_dir():
            continue
        body = "\n".join(f"    {block}" for block in blocks)
        target.write_text(
            f"{preamble}{open_tag}\n{body}\n</urlset>\n", encoding="utf-8"
        )
        written += 1
    return written


# -- deployment surface ------------------------------------------------------
#
# Three files depend on where the site is deployed rather than on any page, so they cannot be
# templates: robots.txt, the root favicon.ico alias and the English variant of the error page.

_POLYGON = re.compile(r'<polygon\b[^>]*?points="([^"]+)"[^>]*?fill="(#[0-9A-Fa-f]{6})"')
_POINT = re.compile(r"(-?\d+(?:\.\d+)?)\s*[,\s]\s*(-?\d+(?:\.\d+)?)")
_VIEWBOX = re.compile(r'viewBox="0 0 (\d+(?:\.\d+)?) (\d+(?:\.\d+)?)"')
_ZH_GROUP = re.compile(r"<!--rmc:404:zh-->.*?<!--/rmc:404:zh-->", re.DOTALL)
_EN_GROUP = re.compile(r"<!--rmc:404:en-->.*?<!--/rmc:404:en-->", re.DOTALL)
FAVICON_SOURCE = ROOT / "docs" / "assets" / "favicon.svg"


def robots_txt(site_url: str) -> str:
    """Return robots.txt for the deployment origin.

    Only a publicly reachable origin advertises its sitemap; a private or loopback origin asks
    crawlers to stay out. This file is an indexing hint and never access control: the server
    answers every page and every error surface whatever it says.
    """
    host = (urlsplit(site_url or "").hostname or "").lower()
    if not host or _private_host(host):
        return "User-agent: *\nDisallow: /\n"
    return f"User-agent: *\nAllow: /\nSitemap: {site_url.rstrip('/')}/sitemap.xml\n"


def _private_host(host: str) -> bool:
    if host in {"localhost", "localhost.localdomain"} or host.endswith(".local"):
        return True
    try:
        return not ipaddress.ip_address(host).is_global
    except ValueError:
        # A public name, not an address literal.
        return False


def svg_polygons(
    svg: str,
) -> list[tuple[list[tuple[float, float]], tuple[int, int, int]]]:
    """Read the filled polygons of an icon mark, in paint order."""
    polygons = []
    for points, fill in _POLYGON.findall(svg):
        ring = [(float(x), float(y)) for x, y in _POINT.findall(points)]
        red, green, blue = (int(fill[index : index + 2], 16) for index in (1, 3, 5))
        polygons.append((ring, (red, green, blue)))
    return polygons


def rasterize(
    polygons: list[tuple[list[tuple[float, float]], tuple[int, int, int]]],
    size: int,
    viewbox: tuple[float, float] = (64.0, 64.0),
) -> list[list[tuple[int, int, int, int]]]:
    """Sample the mark at pixel centres, painting the polygons in order."""
    width, height = viewbox
    scale_x, scale_y = width / size, height / size
    pixels = []
    for row in range(size):
        y = (row + 0.5) * scale_y
        line = []
        for column in range(size):
            x = (column + 0.5) * scale_x
            colour = (0, 0, 0, 0)
            for ring, fill in polygons:
                if _inside(ring, x, y):
                    colour = (*fill, 255)
            line.append(colour)
        pixels.append(line)
    return pixels


def _inside(ring: list[tuple[float, float]], x: float, y: float) -> bool:
    """Even-odd test against one closed ring."""
    inside = False
    count = len(ring)
    for index in range(count):
        x1, y1 = ring[index]
        x2, y2 = ring[(index + 1) % count]
        if (y1 > y) != (y2 > y):
            crossing = x1 + (y - y1) * (x2 - x1) / (y2 - y1)
            if x < crossing:
                inside = not inside
    return inside


def png_bytes(pixels: list[list[tuple[int, int, int, int]]]) -> bytes:
    """Encode an RGBA raster as a PNG, so one ico entry can carry it as-is."""
    size = len(pixels)
    raw = bytearray()
    for line in pixels:
        raw.append(0)
        for pixel in line:
            raw.extend(pixel)
    return (
        b"\x89PNG\r\n\x1a\n"
        + _chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
        + _chunk(b"IDAT", zlib.compress(bytes(raw), 9))
        + _chunk(b"IEND", b"")
    )


def _chunk(tag: bytes, data: bytes) -> bytes:
    crc = zlib.crc32(tag + data) & 0xFFFFFFFF
    return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", crc)


def ico_bytes(images: dict[int, bytes]) -> bytes:
    """Wrap PNG payloads as a multi-size Windows icon."""
    entries = bytearray()
    payload = bytearray()
    offset = 6 + 16 * len(images)
    for size in sorted(images):
        data = images[size]
        entries.extend(
            struct.pack(
                "<BBBBHHII",
                size & 0xFF,
                size & 0xFF,
                0,
                0,
                1,
                32,
                len(data),
                offset + len(payload),
            )
        )
        payload.extend(data)
    return struct.pack("<HHH", 0, 1, len(images)) + bytes(entries) + bytes(payload)


def favicon_ico(svg: str, sizes: tuple[int, ...] = (16, 32)) -> bytes:
    """Render the shipped SVG mark into an ico, so /favicon.ico needs no renderer at build time."""
    polygons = svg_polygons(svg)
    found = _VIEWBOX.search(svg)
    viewbox = (float(found.group(1)), float(found.group(2))) if found else (64.0, 64.0)
    return ico_bytes(
        {size: png_bytes(rasterize(polygons, size, viewbox)) for size in sizes}
    )


def english_error_variant(html: str) -> str:
    """Put the English entry group first in the error page, keeping every other byte."""
    chinese, english = _ZH_GROUP.search(html), _EN_GROUP.search(html)
    if chinese is None or english is None or english.start() < chinese.start():
        return html
    return (
        html[: chinese.start()]
        + english.group(0)
        + html[chinese.end() : english.start()]
        + chinese.group(0)
        + html[english.end() :]
    )


def write_deployment_files(site: Path, site_url: str) -> list[str]:
    """Write the files that follow the deployment origin instead of the page tree."""
    written = ["robots.txt"]
    (site / "robots.txt").write_text(
        robots_txt(site_url), encoding="utf-8", newline="\n"
    )
    icon = favicon_ico(FAVICON_SOURCE.read_text(encoding="utf-8"))
    for relative in ("favicon.ico", "assets/favicon.ico"):
        target = site / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(icon)
        written.append(relative)
    return written


_ERROR_MARKER = re.compile(r"<!--/?rmc:404:(?:zh|en)-->")


def strip_error_markers(html: str) -> str:
    """Remove the build markers, so the shipped page carries no internal bookkeeping."""
    return _ERROR_MARKER.sub("", html)


def error_page_for(html: str, language: str) -> str:
    """Order an error page's entry groups so the page's own language comes first."""
    return english_error_variant(html) if language == "en" else html


def primary_language(config) -> str:
    """The language the site serves at its root, taken from the i18n configuration."""
    plugin = config.plugins.get("i18n")
    entries = plugin.config.get("languages") if plugin is not None else None
    for entry in entries or []:
        if entry.get("default"):
            return entry.get("locale", "zh")
    return "zh"


def language_home(language: str, config) -> str:
    """The home page of one language, as a path from the deployment root.

    The error page answers a missing path, so its language entries leave the page tree and point
    at the site roots: the deployment root for the primary language and a directory per other
    language, which is `/` and `/en/` for a site served from the domain root.
    """
    base = urlsplit(config.site_url or "/").path or "/"
    if not base.endswith("/"):
        base += "/"
    if not language or language == primary_language(config):
        return base
    return f"{base}{language}/"


def on_template_context(context, template_name, config):
    """Point the error page's language switcher at the two home pages.

    static-i18n rewrites ``extra.alternate`` after each page so the switcher offers the same
    page in another language, and leaves the last page's list on the config. The error page is
    not in the page tree, so those links would send a visitor who mistyped a URL to whichever
    tool page rendered last. The plugin stores that list as an attribute, which Jinja reads
    before a key, so both spellings have to carry the home pages.
    """
    if template_name != "404.html":
        return context
    entries = config.extra.get("alternate") or []
    if not entries:
        return context
    homes = [
        {**entry, "link": language_home(entry.get("lang", ""), config)}
        for entry in entries
    ]
    config.extra["alternate"] = homes
    config.extra.alternate = homes
    return context


#: The error page every language pass rendered, keyed by language. Each pass writes the same file,
#: so a later pass would replace an earlier one; the renders are kept apart and published together.
_ERROR_RENDERS: dict[str, str] = {}


def remember_error_page(site: Path, language: str) -> bool:
    """Keep the error page the current language pass rendered, before the next pass overwrites it."""
    page = site / "404.html"
    if not page.is_file():
        return False
    _ERROR_RENDERS[language] = page.read_text(encoding="utf-8")
    return True


def write_error_pages(site: Path, primary: str = "zh") -> list[str]:
    """Ship one error page per rendered language, with the primary language at the root.

    A single-language build renders one copy, which already sits at the root; every other
    language is written under its own directory. The shipped copies drop the build markers.
    """
    pages = dict(_ERROR_RENDERS)
    root = site / "404.html"
    if not pages:
        if not root.is_file():
            return []
        pages[primary] = root.read_text(encoding="utf-8")
    if primary not in pages:
        primary = next(iter(pages))
    written = []
    for language, html in pages.items():
        relative = "404.html" if language == primary else f"{language}/404.html"
        target = site / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(
            strip_error_markers(error_page_for(html, language)), encoding="utf-8"
        )
        written.append(relative)
    return written


def _catalog_module():
    """Load the catalog manifest module the site generators use, so nothing here hard-codes a version."""
    name = "rmm_catalogs"
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, ROOT / "tools/site/catalogs.py")
    module = importlib.util.module_from_spec(spec)
    # Register before executing: the module declares dataclasses, which look themselves up in
    # sys.modules while the class body is built.
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def _catalog_surfaces() -> dict[str, dict]:
    """Map each catalog directory to the status fields a search result shows."""
    module = _catalog_module()
    release, integration = module.release(), module.integration()
    return {
        release.directory: {
            "catalog": "release",
            "status": release.status,
            "version": release.version,
            "branch": release.branch,
        },
        integration.directory: {
            "catalog": "branch",
            "status": integration.status,
            "version": "",
            "branch": integration.branch,
        },
    }


def search_record(location: str, surfaces: dict[str, dict] | None = None) -> dict:
    """Describe one search index entry by language, tool name and catalog status.

    The search plugin indexes every page in one file, so a result cannot tell a Chinese page from
    an English one or a released tool from a branch-only tool. These fields make both readable
    without a second request.
    """
    surfaces = surfaces or _catalog_surfaces()
    lang = "en" if location.startswith("en/") else "zh"
    relative = location[len("en/") :] if lang == "en" else location
    path = relative.split("#", 1)[0]
    record: dict = {"lang": lang, "tool": None}
    found = TOOL_PAGE.fullmatch(path)
    for directory, surface in surfaces.items():
        if path == directory or path.startswith(f"{directory}/"):
            record.update(surface)
            break
    if found:
        record["tool"] = found.group("tool")
    return record


def enrich_search_index(site: Path) -> int:
    """Add language, tool name and catalog status to every entry of the built search index."""
    index = site / "search/search_index.json"
    if not index.is_file():
        return 0
    data = json.loads(index.read_text(encoding="utf-8"))
    surfaces = _catalog_surfaces()
    for doc in data.get("docs") or []:
        doc.update(search_record(doc.get("location", ""), surfaces))
    index.write_text(
        json.dumps(data, ensure_ascii=False, separators=(",", ":")), encoding="utf-8"
    )
    return len(data.get("docs") or [])


# The search plugin writes its index after the hooks' own post-build event, so the enrichment runs
# at shutdown instead: that is the only point where the index every language build writes exists.
SITE_DIR: Path | None = None


def on_config(config):
    """Remember the top-level site directory, which stays the same for every language build."""
    global SITE_DIR
    if SITE_DIR is None:
        SITE_DIR = Path(config.site_dir)
    return config


def on_shutdown() -> None:
    if SITE_DIR is not None:
        enrich_search_index(SITE_DIR)


def on_post_build(config) -> None:
    site = Path(config.site_dir)
    # The build renders the error page once per language pass into the same file, so this pass
    # keeps its own copy before the next one overwrites it.
    remember_error_page(site, config.theme.get("language") or primary_language(config))
    _write_directory_sitemaps(site, config.site_url or "")
    # The deployment surface and the error pages follow the build configuration, not any page, so
    # they are written here rather than rendered from a template.
    write_deployment_files(site, config.site_url or "")
    write_error_pages(site, primary_language(config))
    # Source maps are a debugging aid for the theme bundle, not site content: shipping them adds
    # 1.2 MB to every deploy for files no visitor requests.
    for source_map in site.rglob("*.map"):
        source_map.unlink()
