"""Resolve included Markdown links relative to their repository source."""

import importlib.util
import json
import posixpath
import re
import sys
from pathlib import Path
from urllib.parse import urlsplit

from markdown import Markdown

ROOT = Path(__file__).resolve().parents[1]
# A tool page's search entry is the only one whose location is a catalog directory followed by a
# stable tool name, optionally with an anchor.
TOOL_PAGE = re.compile(
    r"(?P<directory>features|platform)/(?P<tool>revit_[a-z0-9_]+)/?$"
)

# Each entry maps the repository files that back a documentation page to its Chinese and English page, so a
# link to any of those files resolves to the page the current language build actually has.
SOURCES = [
    (["README.md"], "index.md", "index.en.md"),
    (["server/README.zh.md", "server/README.md"], "server.md", "server.en.md"),
    (
        ["CONTRIBUTING.zh.md", "CONTRIBUTING.md"],
        "contributing.md",
        "contributing.en.md",
    ),
    (["SECURITY.zh.md", "SECURITY.md"], "security-policy.md", "security-policy.en.md"),
    (["CHANGELOG.zh.md", "CHANGELOG.md"], "changelog.md", "changelog.en.md"),
]


def on_page_markdown(markdown, page, config, files):
    root = Path(config.config_file_path).parent
    for sources, chinese_page, english_page in SOURCES:
        if page.file.src_uri == chinese_page:
            source = sources[0]
            break
        if page.file.src_uri == english_page:
            source = sources[-1]
            break
    else:
        source = f"docs/{page.file.src_uri}"
    # Expand snippets before MkDocs validates links, retaining one source of content.
    processor = Markdown(
        extensions=["pymdownx.snippets"],
        extension_configs={
            "pymdownx.snippets": {"base_path": [str(root)], "check_paths": True}
        },
    )
    markdown = "\n".join(processor.preprocessors["snippet"].run(markdown.splitlines()))
    # One repository file can back more than one page (the README backs the Chinese landing page and the
    # English home), so keep every candidate and prefer the one this language build actually has.
    pages: dict[str, list[str]] = {}
    for sources, chinese_page, english_page in SOURCES:
        for repository_file in sources:
            pages.setdefault(repository_file, []).extend([chinese_page, english_page])
    src_uri = page.file.src_uri
    if src_uri in ("index.md", "index.en.md"):
        # The landing page is generated by tools/site/landing.py, so its "edit this page" link has to
        # point at the generator: editing index.md or README.md would be overwritten on the next run.
        page.edit_url = f"{config.repo_url}/blob/main/tools/site/landing.py"
    elif src_uri.startswith("features/"):
        # Same rule for the generated feature pages.
        page.edit_url = f"{config.repo_url}/blob/main/tools/site/generate_features.py"
    elif src_uri.startswith("platform/"):
        # Same rule for the platform catalog, which tools/site/platform_catalog.py generates.
        page.edit_url = f"{config.repo_url}/blob/main/tools/site/platform_catalog.py"
    elif any(src_uri == pair[1] or src_uri == pair[2] for pair in SOURCES):
        # Hand-written pages keep the edit link of the repository file that holds their content.
        page.edit_url = f"{config.repo_url}/edit/main/{source}"

    def resolve(target):
        if target.startswith(config.site_url):
            relative = target[len(config.site_url) :]
            path, separator, anchor = relative.partition("#")
            candidate = f"{path.rstrip('/')}.md" if path else "index.md"
            if files.get_file_from_path(candidate):
                return candidate + (separator + anchor if separator else "")
        url = urlsplit(target)
        if url.scheme or url.netloc or not url.path:
            return target
        path = posixpath.normpath(posixpath.join(posixpath.dirname(source), url.path))
        suffix = (f"?{url.query}" if url.query else "") + (
            f"#{url.fragment}" if url.fragment else ""
        )
        if path in pages:
            for candidate in pages[path]:
                if files.get_file_from_path(candidate):
                    return candidate + suffix
            return pages[path][0] + suffix
        if path.startswith("docs/"):
            return (
                posixpath.relpath(path[5:], posixpath.dirname(page.file.src_uri))
                + suffix
            )
        if (root / path).is_file():
            return f"{config.repo_url}/blob/main/{path}{suffix}"
        return target

    # Pages generated by tools/site/landing.py mark shared assets with @@ROOT@@; resolve it before
    # link resolution so the result is an ordinary relative path.
    markdown = markdown.replace("@@ROOT@@", site_root_prefix(page))
    markdown = re.sub(
        r"(\]\()([^\s)]+)(\))", lambda m: m[1] + resolve(m[2]) + m[3], markdown
    )
    markdown = re.sub(
        r'(\b(?:src|srcset)=")([^"]+)(")',
        lambda m: m[1] + resolve(m[2]) + m[3],
        markdown,
    )
    return markdown


def site_root_prefix(page) -> str:
    """Relative path from one page back to the site root, for assets shared by every language.

    MkDocs already reports the locale as part of `page.url` (`en/`, `en/features/`), which is why the
    theme's own `url` filter emits `../assets/...` on `/en/`. Raw HTML from the page generator cannot
    use that filter, so the same count of `../` is derived from the page URL here.
    """
    depth = len([part for part in page.url.split("/") if part])
    return "../" * depth


_URL_BLOCK = re.compile(r"<url>.*?</url>", re.DOTALL)
_LOC = re.compile(r"<loc>([^<]+)</loc>")


def _write_directory_sitemaps(site: Path) -> int:
    """Give every directory with a page its own sitemap.

    Material resolves the alternate-language lookup as `new URL("sitemap.xml", pageUrl)`, so a page at
    /features/revit_ping/ asks for /features/revit_ping/sitemap.xml and gets a 404. Every directory
    that holds a page therefore gets its own sitemap containing that directory's entries, so the
    lookup succeeds and stays truthful.
    """
    sitemap = site / "sitemap.xml"
    if not sitemap.is_file():
        return 0
    text = sitemap.read_text(encoding="utf-8")
    start = text.find("<urlset")
    if start < 0:
        return 0
    head, open_end = text[:start], text.find(">", start) + 1
    preamble, open_tag = head, text[start:open_end]
    groups: dict[str, list[str]] = {}
    for block in _URL_BLOCK.findall(text):
        found = _LOC.search(block)
        if not found:
            continue
        path = urlsplit(found.group(1)).path
        directory = path if path.endswith("/") else posixpath.dirname(path) + "/"
        if directory != "/":
            groups.setdefault(directory, []).append(block.strip())
    written = 0
    for directory, blocks in groups.items():
        target = site / directory.lstrip("/") / "sitemap.xml"
        if target == sitemap or not target.parent.is_dir():
            continue
        body = "\n".join(f"    {block}" for block in blocks)
        target.write_text(
            f"{preamble}{open_tag}\n{body}\n</urlset>\n", encoding="utf-8"
        )
        written += 1
    return written


def _catalog_module():
    """Load the catalog manifest module the site generators use, so nothing here hard-codes a version."""
    name = "rmm_catalogs"
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, ROOT / "tools/site/catalogs.py")
    module = importlib.util.module_from_spec(spec)
    # Register before executing: the module declares dataclasses, which look themselves up in
    # sys.modules while the class body is built.
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def _catalog_surfaces() -> dict[str, dict]:
    """Map each catalog directory to the status fields a search result shows."""
    module = _catalog_module()
    release, integration = module.release(), module.integration()
    return {
        release.directory: {
            "catalog": "release",
            "status": release.status,
            "version": release.version,
            "branch": release.branch,
        },
        integration.directory: {
            "catalog": "branch",
            "status": integration.status,
            "version": "",
            "branch": integration.branch,
        },
    }


def search_record(location: str, surfaces: dict[str, dict] | None = None) -> dict:
    """Describe one search index entry by language, tool name and catalog status.

    The search plugin indexes every page in one file, so a result cannot tell a Chinese page from
    an English one or a released tool from a branch-only tool. These fields make both readable
    without a second request.
    """
    surfaces = surfaces or _catalog_surfaces()
    lang = "en" if location.startswith("en/") else "zh"
    relative = location[len("en/") :] if lang == "en" else location
    path = relative.split("#", 1)[0]
    record: dict = {"lang": lang, "tool": None}
    found = TOOL_PAGE.fullmatch(path)
    for directory, surface in surfaces.items():
        if path == directory or path.startswith(f"{directory}/"):
            record.update(surface)
            break
    if found:
        record["tool"] = found.group("tool")
    return record


def enrich_search_index(site: Path) -> int:
    """Add language, tool name and catalog status to every entry of the built search index."""
    index = site / "search/search_index.json"
    if not index.is_file():
        return 0
    data = json.loads(index.read_text(encoding="utf-8"))
    surfaces = _catalog_surfaces()
    for doc in data.get("docs") or []:
        doc.update(search_record(doc.get("location", ""), surfaces))
    index.write_text(
        json.dumps(data, ensure_ascii=False, separators=(",", ":")), encoding="utf-8"
    )
    return len(data.get("docs") or [])


# The search plugin writes its index after the hooks' own post-build event, so the enrichment runs
# at shutdown instead: that is the only point where the index every language build writes exists.
SITE_DIR: Path | None = None


def on_config(config):
    """Remember the top-level site directory, which stays the same for every language build."""
    global SITE_DIR
    if SITE_DIR is None:
        SITE_DIR = Path(config.site_dir)
    return config


def on_shutdown() -> None:
    if SITE_DIR is not None:
        enrich_search_index(SITE_DIR)


def on_post_build(config) -> None:
    site = Path(config.site_dir)
    _write_directory_sitemaps(site)
    # Source maps are a debugging aid for the theme bundle, not site content: shipping them adds
    # 1.2 MB to every deploy for files no visitor requests.
    for source_map in site.rglob("*.map"):
        source_map.unlink()
